import test from 'node:test';
import assert from 'node:assert/strict';
import {integerWords, roomDescription, speechChunks, speechText} from '../../frontend/js/speech.js';

const cases = [
  ['42 000 000 ₽', 'сорок два миллиона рублей'],
  ['42\u00a0000\u00a0000 ₽', 'сорок два миллиона рублей'],
  ['42\u202f000\u202f000 ₽', 'сорок два миллиона рублей'],
  ['42000000 руб.', 'сорок два миллиона рублей.'],
  ['Бюджет 42 000 000', 'Бюджет сорок два миллиона'],
  ['до 1,5 млн ₽', 'до одного миллиона пятисот тысяч рублей'],
  ['до 15,5%', 'до пятнадцати целых пяти десятых процента'],
  ['1–2 комнаты', 'от одной комнаты до двух комнат'],
  ['1 комната', 'одна комната'],
  ['42 млн. Это предел.', 'сорок два миллиона. Это предел.'],
  ['42 млн', 'сорок два миллиона'],
  ['42 млн ₽', 'сорок два миллиона рублей'],
  ['9,5 млн ₽', 'девять миллионов пятьсот тысяч рублей'],
  ['5.5 млн', 'пять миллионов пятьсот тысяч'],
  ['1,25 млрд ₽', 'один миллиард двести пятьдесят миллионов рублей'],
  ['266,7 тыс. ₽', 'двести шестьдесят шесть тысяч семьсот рублей'],
  ['9,000001 млн ₽', 'девять миллионов один рубль'],
  ['1 ₽', 'один рубль'], ['2 ₽', 'два рубля'], ['5 ₽', 'пять рублей'],
  ['21 ₽', 'двадцать один рубль'], ['11 ₽', 'одиннадцать рублей'],
  ['0,01 ₽', 'ноль рублей одна копейка'],
  ['1 234,56 ₽', 'одна тысяча двести тридцать четыре рубля пятьдесят шесть копеек'],
  ['−500 ₽', 'минус пятьсот рублей'],
  ['15,5%', 'пятнадцать целых пять десятых процента'],
  ['0,05%', 'ноль целых пять сотых процента'],
  ['6%', 'шесть процентов'], ['21%', 'двадцать один процент'],
  ['53,4 м²', 'пятьдесят три целых четыре десятых квадратного метра'],
  ['21 м²', 'двадцать один квадратный метр'],
  ['22 кв. м', 'двадцать два квадратных метра'],
  ['1 500 ₽/мес', 'одна тысяча пятьсот рублей в месяц'],
  ['8–10 млн', 'от восьми миллионов до десяти миллионов'],
  ['от 8 до 10 млн', 'от восьми миллионов до десяти миллионов'],
  ['8–10 млн ₽', 'от восьми миллионов рублей до десяти миллионов рублей'],
  ['до 42 млн ₽, не выше', 'до сорока двух миллионов рублей, не выше'],
];
for (const [input, expected] of cases) test(input, () => assert.equal(speechText(input), expected));

test('не теряет отрицания, точные суммы и слова после дроби', () => {
  const input = 'Не выше 42 000 001 ₽. Ставка 15,5%, а не 6%.';
  const output = speechText(input);
  assert.equal(output, 'Не выше сорока двух миллионов одного рубля. Ставка пятнадцать целых пять десятых процента, а не шесть процентов.');
  assert.equal(speechText(output), output);
});
test('альтернативы комнат не превращаются в диапазон', () => {
  assert.equal(roomDescription([1,3]), 'одна комната или три комнаты');
  assert.equal(roomDescription([0,1]), 'студия или одна комната');
});
test('нулевые группы и женский род тысяч', () => {
  assert.equal(integerWords(21_001), 'двадцать одна тысяча один');
  assert.equal(integerWords(1_000_001), 'один миллион один');
  assert.equal(integerWords(0), 'ноль');
});
test('дробь не разрывается как предложение, длинный ответ не теряет слова', () => {
  const input = 'Площадь 53,4 м². ' + 'Покажу подходящие квартиры. '.repeat(30);
  const chunks = speechChunks(input);
  assert.ok(chunks.every(c => c.length <= 220));
  assert.equal(chunks.join(' '), speechText(input));
});
test('URL и разметка не зачитываются вместо текста', () => {
  assert.equal(speechText('**Циан:** [посмотреть](https://cian.ru/flat/42/) → 42 млн ₽'), 'Циан: посмотреть сорок два миллиона рублей');
});

test('телефоны и время не превращаются в цену', () => {
  assert.equal(speechText('Телефон +7 900 000 00 00, встреча в 12:30'), 'Телефон +7 900 000 00 00, встреча в 12:30');
});
